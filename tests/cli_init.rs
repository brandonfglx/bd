mod common;

use std::fs;
use std::path::Path;

use predicates::prelude::*;
use tempfile::TempDir;
use time::OffsetDateTime;
use time::macros::format_description;

use common::{assert_contains, assert_date, assert_not_contains, bd, read, write};

fn init_ok(blog: &Path) {
	bd().arg("init").arg(blog).assert().success();
}

fn local_date() -> String {
	let now = OffsetDateTime::now_local().unwrap_or_else(|_| OffsetDateTime::now_utc());
	now.date()
		.format(format_description!("[year]-[month]-[day]"))
		.unwrap()
}

#[test]
fn init_creates_blog_structure() {
	let temp = TempDir::new().unwrap();
	let blog = temp.path().join("blog");

	init_ok(&blog);

	let config_text = read(blog.join("blog.toml"));
	let config: toml::Value = toml::from_str(&config_text).expect("blog.toml should be valid TOML");
	assert_eq!(config["title"].as_str(), Some("My Blog"));
	assert_eq!(
		config["description"].as_str(),
		Some("Auto-generated blog by bd")
	);
	assert_eq!(config["author"].as_str(), Some("User"));
	assert_eq!(config["language"].as_str(), Some("en"));
	assert_eq!(config["build"]["output"].as_str(), Some("build"));
	assert_eq!(config["build"]["include_drafts"].as_bool(), Some(false));

	let gitignore = read(blog.join(".gitignore"));
	assert_contains(&gitignore, "/build");
	assert_contains(&gitignore, ".DS_Store");
	assert_contains(&gitignore, "Thumbs.db");

	let workflow = read(blog.join(".github/workflows/pages.yml"));
	assert_contains(&workflow, "brandonfglx/bd");
	assert_contains(&workflow, env!("CARGO_PKG_VERSION"));
	assert_contains(&workflow, "bd\" build");
	assert_not_contains(&workflow, "__BD_");

	let page_text = read(blog.join("my-page/page.toml"));
	let page: toml::Value = toml::from_str(&page_text).expect("page.toml should be valid TOML");
	assert_eq!(page["title"].as_str(), Some("My First Page"));
	assert_eq!(page["description"].as_str(), Some("My first post."));
	assert_eq!(page["draft"].as_bool(), Some(false));
	assert_eq!(page["content"].as_str(), Some("page.md"));
	assert_date(page["date"].as_str().unwrap());
	let expected_date = local_date();
	assert_eq!(page["date"].as_str(), Some(expected_date.as_str()));
	assert!(!read(blog.join("my-page/page.md")).trim().is_empty());

	for name in ["base.html", "index.html", "post.html"] {
		let template = read(blog.join("templates").join(name));
		assert!(
			!template.trim().is_empty(),
			"templates/{name} should not be empty"
		);
	}
	assert_contains(
		&read(blog.join("templates/base.html")),
		"{{ static_root }}style.css",
	);
	assert_contains(
		&read(blog.join("templates/index.html")),
		"{% block content %}",
	);
	assert_contains(
		&read(blog.join("templates/post.html")),
		"{{ content|safe }}",
	);

	assert!(blog.join("static/style.css").is_file());
	assert_contains(&read(blog.join("static/style.css")), "Site-wide");

	let readme = read(blog.join("README.md"));
	assert_contains(&readme, "# My Blog");
	assert_contains(&readme, "generated by");

	assert!(blog.join(".git").is_dir());
}

#[test]
fn init_creates_nested_directories() {
	let temp = TempDir::new().unwrap();
	let blog = temp.path().join("nested/blog");

	init_ok(&blog);

	assert!(blog.join("blog.toml").is_file());
	assert!(blog.join("my-page/page.md").is_file());
	assert!(blog.join("templates/base.html").is_file());
	assert!(blog.join("static/style.css").is_file());
}

#[test]
fn init_reports_next_steps() {
	let temp = TempDir::new().unwrap();
	let blog = temp.path().join("blog");

	bd().arg("init")
		.arg(&blog)
		.assert()
		.success()
		.stdout(predicate::str::contains("Next steps:"))
		.stdout(predicate::str::contains("bd add"))
		.stdout(predicate::str::contains("blog.toml"))
		.stdout(predicate::str::contains("bd publish"));
}

#[test]
fn init_refuses_existing_blog() {
	let temp = TempDir::new().unwrap();
	write(temp.path().join("blog.toml"), "title = \"Existing\"\n");

	bd().arg("init")
		.arg(temp.path())
		.assert()
		.failure()
		.stderr(predicate::str::contains("already contains blog.toml"));

	assert_eq!(
		read(temp.path().join("blog.toml")),
		"title = \"Existing\"\n"
	);
}

