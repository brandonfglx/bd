#[test]
fn init_preserves_existing_readme_and_gitignore() {
	let temp = TempDir::new().unwrap();
	write(temp.path().join("README.md"), "# Custom\n");
	write(temp.path().join(".gitignore"), "target\n");

	init_ok(temp.path());

	assert_eq!(read(temp.path().join("README.md")), "# Custom\n");
	let gitignore = read(temp.path().join(".gitignore"));
	assert_contains(&gitignore, "target");
	assert_contains(&gitignore, "/build");
}

#[test]
fn init_does_not_reinitialize_existing_git_repository() {
	let temp = TempDir::new().unwrap();
	fs::create_dir(temp.path().join(".git")).unwrap();

	init_ok(temp.path());

	assert!(temp.path().join(".git").is_dir());
	assert!(temp.path().join("blog.toml").is_file());
}
